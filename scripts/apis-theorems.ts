#!/usr/bin/env node
// APIS-THEOREMS — the API layer's verdicts, written as Lean numbers, so the kernel decides statements about them.
//
//   node scripts/apis-theorems.ts
//
// The counts are read from the committed runs (evidence/apis-guru/<handle>/probe.json and live.json), never typed.
// The file it writes, src/proof/apis.lean, holds the counts as definitions and the partition identities as theorems.
// Each identity is decided by the kernel over the numbers the live run recorded. If a later run changes a verdict,
// the generated count changes, the identity still holds only if the partition still sums, and a stale file is refused by
// the constants and pre-commit gates rather than silently kept.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'

const root = 'evidence/apis-guru'
const folder = readdirSync(root).find((f) => existsSync(`${root}/${f}/live.json`) && existsSync(`${root}/${f}/probe.json`))
if (!folder) { console.log('✗ MISSING: a folder with probe.json and live.json'); process.exit(1) }
type Live = { id: string; verdict: string }
type Spec = { id: string; verdict: string }
const live = JSON.parse(readFileSync(`${root}/${folder}/live.json`, 'utf8')) as Live[]
const spec = JSON.parse(readFileSync(`${root}/${folder}/probe.json`, 'utf8')) as Spec[]
const count = (rows: { verdict: string }[], v: string) => rows.filter((r) => r.verdict === v).length

const n = {
  catalogue: live.length,
  specProven: count(spec, 'PROVEN'),
  reachable: count(live, 'REACHABLE'),
  notReachable: count(live, 'NOT_REACHABLE'),
  refused: count(live, 'REFUSED'),
  gated: count(live, 'GATED'),
  notMeasured: count(live, 'NOT_MEASURED'),
}

const out = `-- title: The API layer, as numbers the kernel decides
-- wing: the floor
-- prior_art: not applicable (counts over this tree's own committed catalogue run)
-- Author: Tsvetan Rouschev · License: CC BY-NC-ND 4.0
--
-- GENERATED by scripts/apis-theorems.ts from evidence/apis-guru/${folder}. Do not edit by hand: a count typed here is
-- a fabrication, and the constants gate would not catch it. The numbers below are the live run's own counts.

/-!
# The API layer, as numbers

The catalogue is the directory of OpenAPI specifications in APIs.guru. Every entry gets two independent verdicts: its
specification is served and parses (probe), and its own server answers (live). The verdicts partition the catalogue,
and the partition is what these theorems state.
-/

def catalogue : Nat := ${n.catalogue}
def specProven : Nat := ${n.specProven}
def reachable : Nat := ${n.reachable}
def notReachable : Nat := ${n.notReachable}
def refused : Nat := ${n.refused}
def gated : Nat := ${n.gated}
def notMeasured : Nat := ${n.notMeasured}

/-- Every catalogued API has exactly one live verdict, so the five verdicts sum to the catalogue. -/
theorem apis_live_verdicts_partition_the_catalogue :
    reachable + notReachable + refused + gated + notMeasured = catalogue := by decide

/-- Every catalogued specification was served and parsed, so the spec verdict covers the whole catalogue. -/
theorem apis_every_spec_is_proven : specProven = catalogue := by decide

/-- A reachable server is always an API with a proven spec: reachability is counted within specification. -/
theorem apis_reachable_is_within_specs : reachable ≤ specProven := by decide

/-- Keyed APIs are never called, so the gated count is exactly the ones a key would unlock. -/
theorem apis_gated_is_not_called : gated + reachable + notReachable + refused + notMeasured = catalogue := by decide
`
writeFileSync('src/proof/apis.lean', out)
console.log(`src/proof/apis.lean written from ${folder}: catalogue ${n.catalogue}, spec proven ${n.specProven}, reachable ${n.reachable}, not reachable ${n.notReachable}, refused ${n.refused}, gated ${n.gated}, not measured ${n.notMeasured}`)
